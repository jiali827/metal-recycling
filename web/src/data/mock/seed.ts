function withSeed<T>(rows: T[], day: string): (T & RecordTimestamps)[] {
  return rows.map((row, index) => ({ ...row, ...seedTimestamps(day, index + 1) }));
}

function withSeedBizDate<T extends { date: string }>(rows: T[]): (T & RecordTimestamps)[] {
  return rows.map((row, index) => ({
    ...row,
    ...seedTimestamps(row.date.slice(0, 10), index + 1),
  }));
}

